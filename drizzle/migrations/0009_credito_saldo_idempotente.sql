-- Credito de saldo idempotente: a tela Clientes gera uma chave (UUID) por lancamento
-- antes da primeira tentativa e a reenvia nas repeticoes. Se a resposta se perder e o
-- gerente salvar de novo, o credito (ou debito) nao entra duas vezes no saldo.

ALTER TABLE public.customer_balance_movements ADD COLUMN IF NOT EXISTS client_key UUID;
ALTER TABLE public.customer_balance_movements ADD COLUMN IF NOT EXISTS client_fingerprint TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS customer_balance_movements_client_key_key
  ON public.customer_balance_movements (customer_id, client_key) WHERE client_key IS NOT NULL;

COMMENT ON COLUMN public.customer_balance_movements.client_key IS 'Idempotency key generated by the screen before the first attempt of a manual balance change.';
COMMENT ON COLUMN public.customer_balance_movements.client_fingerprint IS 'Hash of the request, to refuse the same key with different data.';

-- A nova versao aceita chamadas sem a chave (parametro opcional), entao a versao da
-- aplicacao que ainda nao envia a chave continua funcionando.
DROP FUNCTION IF EXISTS public.adjust_customer_balance(uuid, uuid, numeric, text);

CREATE OR REPLACE FUNCTION public.adjust_customer_balance(_store_id uuid, _customer_id uuid, _delta numeric, _reason text DEFAULT 'credito', _client_key uuid DEFAULT NULL)
 RETURNS numeric
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
DECLARE
  _balance NUMERIC(10,2);
  _fingerprint TEXT;
  _existing_fingerprint TEXT;
BEGIN
  IF _delta IS NULL OR _delta = 0 THEN
    RAISE EXCEPTION 'Informe um valor';
  END IF;
  SELECT balance INTO _balance FROM public.customers
  WHERE id = _customer_id AND store_id = _store_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Cliente nao encontrado';
  END IF;
  -- Idempotencia: a mesma chave nunca vira dois lancamentos. A trava do cliente (FOR
  -- UPDATE acima) ja serializa tentativas simultaneas. Uma repeticao devolve o saldo
  -- atual sem lancar de novo; a mesma chave com outro valor e recusada.
  IF _client_key IS NOT NULL THEN
    _fingerprint := md5(concat_ws('|', _delta::text, coalesce(btrim(_reason), '')));
    SELECT client_fingerprint INTO _existing_fingerprint
    FROM public.customer_balance_movements
    WHERE customer_id = _customer_id AND client_key = _client_key;
    IF FOUND THEN
      IF _existing_fingerprint IS DISTINCT FROM _fingerprint THEN
        RAISE EXCEPTION 'lancamento_ja_registrado_com_outros_dados';
      END IF;
      RETURN _balance;
    END IF;
  END IF;
  IF _balance + _delta < 0 THEN
    RAISE EXCEPTION 'Saldo insuficiente: o cliente tem R$ %', to_char(_balance, 'FM999999990.00');
  END IF;
  UPDATE public.customers SET balance = balance + _delta WHERE id = _customer_id
  RETURNING balance INTO _balance;
  INSERT INTO public.customer_balance_movements (customer_id, delta, balance_after, reason, client_key, client_fingerprint)
  VALUES (_customer_id, _delta, _balance, coalesce(nullif(btrim(_reason), ''), 'credito'), _client_key, _fingerprint);
  RETURN _balance;
END;
$function$;

REVOKE ALL ON FUNCTION public.adjust_customer_balance(uuid, uuid, numeric, text, uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.adjust_customer_balance(uuid, uuid, numeric, text, uuid) TO service_role;
