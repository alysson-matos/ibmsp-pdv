-- Venda idempotente: o caixa gera uma chave (UUID) por venda antes da primeira
-- tentativa e a reenvia nas repeticoes. Se a resposta se perder e o operador finalizar
-- de novo, a venda nao entra duas vezes (estoque e saldo do cliente baixam uma vez so).

ALTER TABLE public.sales ADD COLUMN IF NOT EXISTS client_key UUID;
ALTER TABLE public.sales ADD COLUMN IF NOT EXISTS client_fingerprint TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS sales_store_client_key_key
  ON public.sales (store_id, client_key) WHERE client_key IS NOT NULL;

COMMENT ON COLUMN public.sales.client_key IS 'Idempotency key generated by the register before the first checkout attempt.';
COMMENT ON COLUMN public.sales.client_fingerprint IS 'Hash of the checkout request, to refuse the same key with different data.';

-- A nova versao aceita chamadas sem a chave (parametro opcional), entao a versao da
-- aplicacao que ainda nao envia a chave continua funcionando.
DROP FUNCTION IF EXISTS public.checkout_sale(uuid, jsonb, text, text, uuid, numeric, numeric, uuid);

CREATE OR REPLACE FUNCTION public.checkout_sale(_store_id uuid, _items jsonb, _payment_method text, _customer_name text DEFAULT ''::text, _operator_id uuid DEFAULT NULL, _discount numeric DEFAULT 0, _amount_received numeric DEFAULT NULL::numeric, _customer_id uuid DEFAULT NULL, _client_key uuid DEFAULT NULL)
 RETURNS uuid
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
DECLARE
  _item JSONB;
  _product public.products%ROWTYPE;
  _qty INTEGER;
  _subtotal NUMERIC(10,2) := 0;
  _total NUMERIC(10,2);
  _change NUMERIC(10,2) := 0;
  _sale_id UUID;
  _operator public.operators%ROWTYPE;
  _customer public.customers%ROWTYPE;
  _balance NUMERIC(10,2);
  _fingerprint TEXT;
  _existing_fingerprint TEXT;
BEGIN
  IF _store_id IS NULL THEN
    RAISE EXCEPTION 'Loja nao informada';
  END IF;
  -- Idempotencia: a mesma chave (gerada no caixa antes da primeira tentativa) nunca
  -- vira duas vendas. Uma repeticao devolve a venda ja gravada; a mesma chave com
  -- outros dados e recusada, em vez de devolver em silencio uma venda diferente.
  IF _client_key IS NOT NULL THEN
    _fingerprint := md5(concat_ws('|',
      _items::text, _payment_method, btrim(coalesce(_customer_name, '')),
      coalesce(_operator_id::text, ''), coalesce(_discount, 0)::text,
      coalesce(_amount_received::text, ''), coalesce(_customer_id::text, '')));
    -- Serializa tentativas simultaneas da mesma venda ate o fim da transacao.
    PERFORM pg_advisory_xact_lock(hashtextextended(_store_id::text || ':' || _client_key::text, 0));
    SELECT id, client_fingerprint INTO _sale_id, _existing_fingerprint
    FROM public.sales WHERE store_id = _store_id AND client_key = _client_key;
    IF FOUND THEN
      IF _existing_fingerprint IS DISTINCT FROM _fingerprint THEN
        RAISE EXCEPTION 'venda_ja_registrada_com_outros_dados';
      END IF;
      RETURN _sale_id;
    END IF;
  END IF;

  IF _payment_method NOT IN ('dinheiro','debito','credito','pix','saldo') THEN
    RAISE EXCEPTION 'Forma de pagamento invalida';
  END IF;
  IF jsonb_array_length(_items) = 0 THEN
    RAISE EXCEPTION 'Carrinho vazio';
  END IF;
  IF _operator_id IS NULL THEN
    RAISE EXCEPTION 'Selecione o operador da venda';
  END IF;
  SELECT * INTO _operator FROM public.operators WHERE id = _operator_id AND store_id = _store_id AND active;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Operador nao encontrado ou inativo';
  END IF;

  IF _payment_method = 'saldo' THEN
    IF NOT EXISTS (SELECT 1 FROM public.stores WHERE id = _store_id AND customer_balance) THEN
      RAISE EXCEPTION 'Esta loja nao aceita pagamento com saldo';
    END IF;
    IF _customer_id IS NULL THEN
      RAISE EXCEPTION 'Selecione o cliente para pagar com saldo';
    END IF;
    -- Locks the customer so two simultaneous sales can't spend the same balance.
    SELECT * INTO _customer FROM public.customers
    WHERE id = _customer_id AND store_id = _store_id AND active FOR UPDATE;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Cliente nao encontrado ou inativo';
    END IF;
    _customer_name := _customer.name;
  ELSE
    _customer_id := NULL;
  END IF;

  IF _customer_name IS NULL OR btrim(_customer_name) = '' THEN
    RAISE EXCEPTION 'Informe o nome do comprador';
  END IF;

  FOR _item IN SELECT * FROM jsonb_array_elements(_items) LOOP
    _qty := (_item->>'quantity')::INTEGER;
    IF _qty IS NULL OR _qty <= 0 THEN
      RAISE EXCEPTION 'Quantidade invalida';
    END IF;
    SELECT * INTO _product FROM public.products
    WHERE id = (_item->>'product_id')::UUID AND store_id = _store_id FOR UPDATE;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Produto nao encontrado';
    END IF;
    IF _product.stock < _qty THEN
      RAISE EXCEPTION 'Estoque insuficiente para %: restam %', _product.name, _product.stock;
    END IF;
    _subtotal := _subtotal + (_product.price * _qty);
  END LOOP;
  IF _discount IS NULL OR _discount < 0 THEN
    _discount := 0;
  END IF;
  IF _discount > _subtotal THEN
    RAISE EXCEPTION 'Desconto maior que o subtotal';
  END IF;
  _total := _subtotal - _discount;
  IF _payment_method = 'dinheiro' AND _amount_received IS NOT NULL THEN
    IF _amount_received < _total THEN
      RAISE EXCEPTION 'Valor recebido menor que o total';
    END IF;
    _change := _amount_received - _total;
  END IF;
  IF _payment_method = 'saldo' AND _customer.balance < _total THEN
    RAISE EXCEPTION 'Saldo insuficiente: % tem R$ % e a compra custa R$ %',
      _customer.name, to_char(_customer.balance, 'FM999999990.00'), to_char(_total, 'FM999999990.00');
  END IF;

  INSERT INTO public.sales (store_id, subtotal, discount, total, payment_method, amount_received, change_amount, customer_name, customer_id, status, operator_id, operator_name, client_key, client_fingerprint)
  VALUES (_store_id, _subtotal, _discount, _total, _payment_method,
          CASE WHEN _payment_method = 'dinheiro' THEN _amount_received ELSE NULL END,
          _change, btrim(_customer_name), _customer_id, 'pendente', _operator.id, _operator.name, _client_key, _fingerprint)
  RETURNING id INTO _sale_id;
  FOR _item IN SELECT * FROM jsonb_array_elements(_items) LOOP
    _qty := (_item->>'quantity')::INTEGER;
    SELECT * INTO _product FROM public.products WHERE id = (_item->>'product_id')::UUID;
    INSERT INTO public.sale_items (sale_id, product_id, product_name, barcode, unit_price, unit_cost, quantity, subtotal)
    VALUES (_sale_id, _product.id, _product.name, _product.barcode, _product.price, NULLIF(_product.cost, 0), _qty, _product.price * _qty);
    UPDATE public.products SET stock = stock - _qty WHERE id = _product.id;
    INSERT INTO public.stock_movements (product_id, delta, reason, sale_id)
    VALUES (_product.id, -_qty, 'venda', _sale_id);
  END LOOP;

  IF _payment_method = 'saldo' AND _total > 0 THEN
    UPDATE public.customers SET balance = balance - _total WHERE id = _customer_id
    RETURNING balance INTO _balance;
    INSERT INTO public.customer_balance_movements (customer_id, delta, balance_after, reason, sale_id)
    VALUES (_customer_id, -_total, _balance, 'venda', _sale_id);
  END IF;
  RETURN _sale_id;
END;
$function$;

REVOKE ALL ON FUNCTION public.checkout_sale(uuid, jsonb, text, text, uuid, numeric, numeric, uuid, uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.checkout_sale(uuid, jsonb, text, text, uuid, numeric, numeric, uuid, uuid) TO service_role;
